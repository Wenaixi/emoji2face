_SORTED_EMOJIS = sorted(EMOJI_TO_QQ_FACE.keys(), key=len, reverse=True)
_EMOJI_REGEX = re.compile("|".join(re.escape(k) for k in _SORTED_EMOJIS))


def split_text_with_faces(text: str) -> List[Dict[str, Any]]:
    """将纯文本切分为 [text, face, text] 消息段列表。"""
    if not text:
        return []

    segments: List[Dict[str, Any]] = []
    last_idx = 0

    for match in _EMOJI_REGEX.finditer(text):
        emoji_char = match.group(0)
        face_id = EMOJI_TO_QQ_FACE.get(emoji_char)

        if not face_id:
            continue

        start, end = match.span()

        if start > last_idx:
            prev_text = text[last_idx:start]
            if prev_text:
                segments.append({"type": "text", "data": prev_text})

        # 构造官方原版适配器原生支持的 face 消息段
        segments.append({"type": "face", "data": {"id": face_id}})
        last_idx = end

    if last_idx < len(text):
        remaining_text = text[last_idx:]
        if remaining_text:
            segments.append({"type": "text", "data": remaining_text})

    return segments if segments else [{"type": "text", "data": text}]


def convert_message_segments(raw_message: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """将出站 raw_message 列表中的 text 消息段递归切分为图文表情段。"""
    if not isinstance(raw_message, list):
        return raw_message

    new_segments: List[Dict[str, Any]] = []
    for item in raw_message:
        if not isinstance(item, dict):
            new_segments.append(item)
            continue

        item_type = str(item.get("type") or "").strip().lower()
        if item_type == "text":
            text_data = str(item.get("data") or "")
            splitted = split_text_with_faces(text_data)
            new_segments.extend(splitted)
        else:
            new_segments.append(item)

    return new_segments
